const card = new Fixture();
card.platform = 'android_tv'; card.calls = [];
card._config = { platform: 'android_tv', tv_entity: 'media_player.tv', remote_entity: 'remote.tv' };
card._hass = { states: {'media_player.tv': {state:'on', attributes:{adb_response:'stale'}}},
  callService: async (domain, service, data) => card.calls.push([domain,service,data]) };
const provider = name => [{provider_name:name,logo_path:'/icon.png',groups:[]}];
const episode = (name, url) => ({type:'tv',selectedSeason:1, selectedEpisode:{episode_number:2},
  episodeSourcesLoading:false,episodeSources:[{name,scope:'episode',season:1,episode:2,
    web_url:url}]});
const render = (name, url) => {card._details = episode(name,url);
  return card._renderProviderCards(card._details,provider(name),true);};
let html = render('Netflix','https://www.netflix.com/title/80000001');
assert(html.includes('provider-action-caption">App</span>'), 'a Netflix series link is not TV episode playback');
assert(html.includes('provider-action-caption">Series</span>'), 'device series link labelled series');
assert(!html.includes('data-title-provider='));
html = render('Netflix','https://www.netflix.com/watch/80123456');
assert(html.includes('data-title-provider="Netflix"'));
assert.equal((html.match(/provider-action-caption">Episode<\/span>/g)||[]).length,2);
card.platform = 'webos';
html = render('Netflix','https://www.netflix.com/watch/80123456');
assert(html.includes('data-open-provider="Netflix"'), 'movie-only webOS Netflix launcher not used for episodes');
assert(!html.includes('data-title-provider='));
card.platform = 'android_tv';
html = render('Prime Video','https://www.primevideo.com/detail/B012345678');
assert(html.includes('provider-action-caption">Series</span>'), 'generic Prime detail ASIN is not proven episode');
assert(html.includes('provider-action-caption">App</span>'));
html = render('Prime Video','https://www.primevideo.com/detail/B012345678?episodeId=E222');
assert(html.includes('data-title-provider="Prime Video"'));
html = render('Crunchyroll','https://www.crunchyroll.com/watch/GR1234567');
assert(html.includes('data-open-provider="Crunchyroll"'));
assert(!html.includes('data-title-provider='));
assert(html.includes('provider-action-caption">Episode</span>'), 'external device link is episode-shaped');
assert(html.includes('provider-action-caption">App</span>'), 'Android TV Crunchyroll button is app');
card._config.adb_entity = '';
assert.equal(card._androidAdbEntity(),null,'ADB is not auto-detected from player attributes');
card._config.adb_entity = 'media_player.adb';
card._hass.states['media_player.adb'] = {state:'on'};
assert.equal(card._androidAdbEntity(),'media_player.adb');
card._config.adb_entity = '';
card._config.manual_profile_selection = false;
card.calls = [];
